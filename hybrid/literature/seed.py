@dataclass(frozen=True)
class SeedEntry:
    lens: str
    paper: Paper
    relevance: str


def check_lens(lens: str) -> None:
    if lens not in LENSES:
        raise ValueError(f"unknown lens {lens!r}")


def load_seed(path: Path = SEED_PATH) -> list[SeedEntry]:
    data = tomllib.loads(Path(path).read_text(encoding="utf-8"))
    entries = []
    for row in data["papers"]:
        check_lens(row["lens"])
        paper = Paper(
            source=row["source"],
            source_id=row["source_id"],
            title=row["title"],
            authors=tuple(row.get("authors", [])),
            year=row.get("year"),
            abstract=row.get("abstract"),
            url=row["url"],
            venue=row.get("venue"),
            citation_count=row.get("citation_count"),
            fetched_at=row["fetched_at"],
            arxiv_id=row.get("arxiv_id"),
            doi=row.get("doi"),
        )
        entries.append(SeedEntry(row["lens"], paper, row["relevance"]))
    return entries


def write_seed(entries: Iterable[SeedEntry], path: Path, generated_at: str) -> None:
    lines = [
        "# Generated by hybrid/literature/build_seed.py from logged keyless searches.",
        "# Change the picks in build_seed.py and rerun it; do not hand-edit this file.",
        f"generated_at = {_toml_str(generated_at)}",
        "",
    ]
    for entry in entries:
        paper = entry.paper
        lines.append("[[papers]]")
        lines.append(f"lens = {_toml_str(entry.lens)}")
        lines.append(f"title = {_toml_str(paper.title)}")
        if paper.year is not None:
            lines.append(f"year = {paper.year}")
        lines.append(f"source = {_toml_str(paper.source)}")
        lines.append(f"source_id = {_toml_str(paper.source_id)}")
        lines.append(f"url = {_toml_str(paper.url)}")
        if paper.arxiv_id is not None:
            lines.append(f"arxiv_id = {_toml_str(paper.arxiv_id)}")
        if paper.doi is not None:
            lines.append(f"doi = {_toml_str(paper.doi)}")
        if paper.venue is not None:
            lines.append(f"venue = {_toml_str(paper.venue)}")
        if paper.citation_count is not None:
            lines.append(f"citation_count = {paper.citation_count}")
        lines.append("authors = [" + ", ".join(_toml_str(name) for name in paper.authors) + "]")
        lines.append(f"fetched_at = {_toml_str(paper.fetched_at)}")
        lines.append(f"relevance = {_toml_str(entry.relevance)}")
        if paper.abstract is not None:
            lines.append(f"abstract = {_toml_str(paper.abstract)}")
        lines.append("")
    Path(path).write_text("\n".join(lines), encoding="utf-8")


def _toml_str(value: str) -> str:
    # JSON string escapes are a subset of TOML basic-string escapes, so json.dumps yields valid TOML.
    return json.dumps(value, ensure_ascii=False)


def write_build_log(rows: Iterable[dict[str, Any]], path: Path = BUILD_LOG_PATH) -> None:
    """Rewrite the log from scratch. Each build reproduces the whole log from the cache,
    so an appended log would only accumulate duplicate rows."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        for row in rows:
            handle.write(json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n")


def search_row(lens: str, receipt: Any) -> dict[str, Any]:
    """One build-log row per search: the lens, the query, and every raw hit per source."""
    return {
        "lens": lens,
        "query": receipt.query,
        "ts": receipt.ts,
        "sources": list(receipt.sources),
        "limit": receipt.limit,
        "errors": dict(receipt.errors),
        "per_source": {
            source: [paper_to_dict(paper) for paper in found] for source, found in receipt.per_source.items()
        },
    }


def read_build_log(path: Path = BUILD_LOG_PATH) -> list[dict[str, Any]]:
    if not Path(path).exists():
        return []
    return [json.loads(line) for line in Path(path).read_text(encoding="utf-8").splitlines() if line]


def cached_search_papers(lens: str, path: Path = BUILD_LOG_PATH) -> list[Paper]:
    """Raw search hits recorded for this lens. These are the cached search results for the lens."""
    papers = []
    for row in read_build_log(path):
        if row["lens"] != lens:
            continue
        for found in row["per_source"].values():
            papers.extend(paper_from_dict(item) for item in found)
    return papers
