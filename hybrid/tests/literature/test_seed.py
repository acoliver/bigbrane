"""The shipped seed list: size, lens coverage, and traceability to logged keyless searches."""
from collections import Counter

from hybrid.literature.seed import KNOWN_ALTERNATIVES_LENS, LENSES, SEED_PATH, load_seed, read_build_log


def test_seed_list_has_between_80_and_120_papers():
    assert 80 <= len(load_seed()) <= 120


def test_every_lens_has_entries_and_counts_are_in_the_spec_range():
    counts = Counter(entry.lens for entry in load_seed())
    for lens in LENSES:
        if lens == KNOWN_ALTERNATIVES_LENS:
            assert 6 <= counts[lens] <= 12, lens
        else:
            assert 3 <= counts[lens] <= 6, lens


def test_known_alternatives_lens_covers_the_named_architectures():
    titles = " | ".join(entry.paper.title for entry in load_seed() if entry.lens == KNOWN_ALTERNATIVES_LENS)
    for keyword in ["Linear", "Mamba", "RWKV", "Retentive", "Hyena", "xLSTM", "BitNet", "Concept", "Test Time"]:
        assert keyword.lower() in titles.lower(), keyword


def test_every_entry_traces_to_a_logged_search_hit_for_its_lens():
    logged = {}
    for row in read_build_log():
        for source, found in row["per_source"].items():
            for item in found:
                logged[(row["lens"], source, item["source_id"])] = item
    for entry in load_seed():
        key = (entry.lens, entry.paper.source, entry.paper.source_id)
        assert key in logged, f"{key} was never returned by a logged search for its lens"
        assert logged[key]["title"] == entry.paper.title
        assert logged[key]["url"] == entry.paper.url


def test_entries_have_metadata_and_one_line_relevance_notes():
    for entry in load_seed():
        assert entry.paper.title and entry.paper.url and entry.paper.year is not None
        assert entry.paper.fetched_at
        assert entry.relevance and "\n" not in entry.relevance
        assert "\u2014" not in entry.relevance  # no em dashes in prose


def test_no_duplicate_papers_across_the_list():
    keys = [(entry.paper.source, entry.paper.source_id) for entry in load_seed()]
    assert len(keys) == len(set(keys))


def test_seed_file_is_generated_with_a_header():
    text = SEED_PATH.read_text(encoding="utf-8")
    assert text.startswith("# Generated by hybrid/literature/build_seed.py")
